package tickscope.stats

import java.nio.charset.StandardCharsets
import java.nio.file.{Files, Path, Paths}

import org.apache.spark.sql.functions._
import tickscope.{Args, Spark}

/** Statistics report on 1-minute bars -> reports/stats.md (+ JSON for the dashboard).
  *
  * sbt "runMain tickscope.stats.StatsJob --bars ../data/features/bars_1m
  *      --report ../reports/stats.md --json ../results/stats.json"
  */
object StatsJob {

  final case class DayRow(date: String, open: Double, close: Double, dayReturn: Double, realizedVol: Double,
                          volume: Double, trades: Long)

  def main(argv: Array[String]): Unit = {
    val opts = Args.parse(argv.toSeq)
    val barsPath = Args.required(opts, "bars")
    val reportPath = Paths.get(Args.required(opts, "report"))
    val jsonPath = opts.get("json").map(Paths.get(_))
    val spark = Spark.local("tickscope-stats")

    try {
      val bars = spark.read.parquet(barsPath).cache()
      val (firstDay, lastDay, nBars) = {
        val r = bars.agg(min("date"), max("date"), count(lit(1))).head()
        (r.get(0).toString, r.get(1).toString, r.getLong(2))
      }

      val ret = Stats.moments(bars, "logReturn")
      val acf = Stats.autocorrelation(bars, "logReturn", "barStartUs", maxLag = 5)
      val pred = Stats.predictive(bars, "imbalance", "logReturn", "barStartUs")
      val absAcf = Stats.autocorrelation(bars.withColumn("absRet", abs(col("logReturn"))), "absRet", "barStartUs", 5)

      // Per-day summary: small (one row per day), so collecting it is fine.
      val days = bars
        .groupBy(col("date"))
        .agg(
          min_by(col("open"), col("barStartUs")).as("open"),
          max_by(col("close"), col("barStartUs")).as("close"),
          sqrt(sum(pow(coalesce(col("logReturn"), lit(0.0)), 2))).as("realizedVol"),
          sum("volume").as("volume"),
          sum("tradeCount").as("trades")
        )
        .orderBy("date")
        .collect()
        .map(r =>
          DayRow(r.get(0).toString, r.getDouble(1), r.getDouble(2), math.log(r.getDouble(2) / r.getDouble(1)),
            r.getDouble(3), r.getDouble(4), r.getLong(5))
        )
        .toSeq

      write(reportPath, report(firstDay, lastDay, nBars, ret, acf, absAcf, pred, days))
      println(s"wrote $reportPath")
      jsonPath.foreach { p =>
        write(p, json(firstDay, lastDay, nBars, ret, acf, absAcf, pred, days))
        println(s"wrote $p")
      }
      bars.unpersist()
    } finally spark.stop()
  }

  private def write(path: Path, text: String): Unit = {
    Option(path.getParent).foreach(Files.createDirectories(_))
    Files.write(path, text.getBytes(StandardCharsets.UTF_8))
  }

  private def f(x: Double, digits: Int = 4): String = s"%.${digits}f".format(x)
  private def e(x: Double): String = "%.3e".format(x)

  /** P(|Z| > 4) for a standard normal: 6.334e-5. */
  val NormalTail4: Double = 6.334e-5

  def report(firstDay: String, lastDay: String, nBars: Long, m: Moments, acf: Seq[Autocorrelation],
             absAcf: Seq[Autocorrelation], p: Predictive, days: Seq[DayRow]): String = {
    val band = 1.96 / math.sqrt(m.n.toDouble)
    val expectedTail = NormalTail4 * m.n
    val sb = new StringBuilder
    sb ++= "# TickScope — Statistics report\n\n"
    sb ++= s"Generated by `StatsJob` from Binance BTCUSDT 1-minute bars, $firstDay to $lastDay " +
      f"($nBars%,d bars). All numbers below are computed by the job; nothing is typed by hand.\n\n"

    sb ++= "## 1. Distribution of 1-minute log returns\n\n"
    sb ++= "| Statistic | Value |\n|---|---|\n"
    sb ++= f"| Observations | ${m.n}%,d |\n"
    sb ++= s"| Mean | ${e(m.mean)} |\n| Std dev | ${e(m.std)} |\n"
    sb ++= s"| Skewness | ${f(m.skew)} |\n| Excess kurtosis | ${f(m.excessKurtosis, 2)} |\n"
    sb ++= s"| Min / max | ${e(m.min)} / ${e(m.max)} |\n"
    sb ++= f"| Moves beyond 4σ | ${m.beyond4Sigma}%,d (a normal distribution would give ~$expectedTail%.1f) |\n\n"
    sb ++= {
      if (m.excessKurtosis > 1)
        s"Excess kurtosis of ${f(m.excessKurtosis, 2)} (normal = 0) means **fat tails**: large one-minute moves " +
          f"are far more common than a normal model predicts — ${m.beyond4Sigma}%,d moves beyond 4σ versus " +
          f"~$expectedTail%.1f expected. A risk model that assumes normal returns would understate tail risk.\n\n"
      else s"Excess kurtosis of ${f(m.excessKurtosis, 2)} is close to normal.\n\n"
    }

    sb ++= "## 2. Autocorrelation of returns\n\n"
    sb ++= f"Under no autocorrelation, estimates fall within ±1.96/√n = ±$band%.4f about 95%% of the time.\n\n"
    sb ++= "| Lag (minutes) | Pairs | ρ(returns) | Outside band? | ρ(\\|returns\\|) |\n|---|---|---|---|---|\n"
    acf.zip(absAcf).foreach { case (a, b) =>
      sb ++= f"| ${a.lag} | ${a.n}%,d | ${f(a.rho)} | ${if (math.abs(a.rho) > band) "yes" else "no"} | ${f(b.rho)} |\n"
    }
    val sig = acf.filter(a => math.abs(a.rho) > band)
    val maxRatio = if (sig.isEmpty) 0.0 else sig.map(a => math.abs(a.rho) / band).max
    sb ++= "\n"
    sb ++= {
      if (sig.isEmpty)
        "Return autocorrelations are all inside the band: past returns carry no usable linear signal about the next minute's direction. "
      else {
        val which = if (sig.size == 1) s"Only lag ${sig.head.lag} falls" else s"Lags ${sig.map(_.lag).mkString(", ")} fall"
        val chance =
          if (sig.size == 1 && maxRatio < 1.5)
            f" and only just (|ρ| = ${math.abs(sig.head.rho)}%.4f vs band $band%.4f). Testing ${acf.size} lags at 5%% gives ~${0.05 * acf.size}%.2f false positives by chance, so this is weak evidence; returns are close to unpredictable from their own past. "
          else ": returns show some linear dependence on their own past at these lags. "
        which + " outside the band" + chance
      }
    }
    sb ++= "Absolute returns are clearly positively autocorrelated (**volatility clustering**): big moves follow big moves, even when their direction is unpredictable. This is also why the next test needs HAC standard errors.\n\n"

    sb ++= "## 3. Does order-flow imbalance predict the next minute's return?\n\n"
    sb ++= "Imbalance(t) = (taker buy volume − taker sell volume) / total volume in minute t. Regression: return(t+1) = a + b · imbalance(t) + e.\n\n"
    sb ++= "| Statistic | Value |\n|---|---|\n"
    sb ++= f"| Pairs (n) | ${p.n}%,d |\n| Pearson r | ${f(p.pearsonR)} |\n| Slope b | ${e(p.slope)} |\n"
    sb ++= s"| t-stat, naive OLS | ${f(p.naiveT, 2)} |\n| t-stat, Newey-West HAC (${p.hacLags} lags) | ${f(p.hacT, 2)} |\n\n"
    val sigNaive = math.abs(p.naiveT) > 1.96
    val sigHac = math.abs(p.hacT) > 1.96
    sb ++= s"r = ${f(p.pearsonR)} means imbalance explains ${f(100 * p.pearsonR * p.pearsonR, 2)}% of the variance of the next minute's return. "
    sb ++= ((sigNaive, sigHac) match {
      case (_, true) =>
        s"The relationship is statistically significant at 5% even with HAC errors (|t| = ${f(math.abs(p.hacT), 2)} > 1.96), with sign ${if (p.slope > 0) "positive: buying pressure is followed by slightly higher prices" else "negative: buying pressure is followed by slightly lower prices (reversal)"}. "
      case (true, false) =>
        s"The naive t-stat says significant, but the HAC t-stat (${f(p.hacT, 2)}) does not: the apparent significance came from ignoring autocorrelated, heteroskedastic errors. "
      case _ =>
        "It is not statistically significant at 5% under either standard error. "
    })
    if (math.abs(p.hacT) > math.abs(p.naiveT))
      sb ++= "Note the HAC t-stat is larger than the naive one here: Newey-West corrects in both directions, and when the products (x − x̄)·e are negatively autocorrelated the long-run variance is smaller than the naive estimate. "
    sb ++= "Even when significant, an effect this small (a fraction of a basis point per minute) is unlikely to survive trading costs at a one-minute horizon; order-flow effects are generally strongest at much shorter horizons, which 1-minute bars average away.\n\n"

    sb ++= "## 4. Daily summary\n\n"
    sb ++= "| Date | Open | Close | Return | Realized vol (√Σr², 1m) | Volume (BTC) | Trades |\n|---|---|---|---|---|---|---|\n"
    days.foreach { d =>
      sb ++= f"| ${d.date} | ${d.open}%,.2f | ${d.close}%,.2f | ${100 * d.dayReturn}%+.2f%% | ${100 * d.realizedVol}%.2f%% | ${d.volume}%,.1f | ${d.trades}%,d |\n"
    }
    sb ++= "\n"
    sb.toString
  }

  def json(firstDay: String, lastDay: String, nBars: Long, m: Moments, acf: Seq[Autocorrelation],
           absAcf: Seq[Autocorrelation], p: Predictive, days: Seq[DayRow]): String = {
    def acfJson(a: Seq[Autocorrelation]) = a.map(x => s"""{"lag": ${x.lag}, "n": ${x.n}, "rho": ${x.rho}}""").mkString("[", ", ", "]")
    val dayJson = days
      .map(d =>
        s"""{"date": "${d.date}", "open": ${d.open}, "close": ${d.close}, "return": ${d.dayReturn}, "realizedVol": ${d.realizedVol}, "volume": ${d.volume}, "trades": ${d.trades}}"""
      )
      .mkString("[\n    ", ",\n    ", "\n  ]")
    s"""{
  "from": "$firstDay", "to": "$lastDay", "bars": $nBars,
  "returns": {"n": ${m.n}, "mean": ${m.mean}, "std": ${m.std}, "skew": ${m.skew}, "excessKurtosis": ${m.excessKurtosis}, "min": ${m.min}, "max": ${m.max}, "beyond4Sigma": ${m.beyond4Sigma}, "normalExpectedBeyond4Sigma": ${NormalTail4 * m.n}},
  "acf": ${acfJson(acf)},
  "absAcf": ${acfJson(absAcf)},
  "imbalancePredictsReturn": {"n": ${p.n}, "r": ${p.pearsonR}, "slope": ${p.slope}, "naiveT": ${p.naiveT}, "hacT": ${p.hacT}, "hacLags": ${p.hacLags}},
  "days": $dayJson
}
"""
  }
}
