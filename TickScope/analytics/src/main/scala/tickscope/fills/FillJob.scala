package tickscope.fills

import java.nio.charset.StandardCharsets
import java.nio.file.{Files, Paths}

import org.apache.spark.sql.functions._
import org.apache.spark.sql.Row
import tickscope.{Args, Spark}

/** Fill analytics -> section 5 of reports/stats.md (replaced on re-run) + results/fills.json.
  *
  * sbt "runMain tickscope.fills.FillJob --fills ../data/fills.csv --orders ../data/orders.csv
  *      --bars ../data/features/bars_1m --prices ../data/prices.csv --clean ../data/clean
  *      --day 2026-11-05 --report ../reports/stats.md --json ../results/fills.json"
  */
object FillJob {
  val Marker = "## 5. Fill analytics"

  def main(argv: Array[String]): Unit = {
    val o = Args.parse(argv.toSeq)
    val spark = Spark.local("tickscope-fills")
    try {
      val started = System.nanoTime()
      val fills = FillAnalytics.readCsv(spark, Args.required(o, "fills"), FillAnalytics.fillSchema).cache()
      val orders = FillAnalytics.readCsv(spark, Args.required(o, "orders"), FillAnalytics.orderSchema)
      val prices = FillAnalytics.readCsv(spark, Args.required(o, "prices"), FillAnalytics.priceSchema)
      val bars = spark.read.parquet(Args.required(o, "bars"))
      val day = Args.required(o, "day")
      // Partition pruning: only the replayed day's directory is read.
      val trades = spark.read.parquet(Args.required(o, "clean")).filter(col("date") === lit(day).cast("date"))

      val rates = FillAnalytics.fillRates(orders).collect().toSeq
      val execs = FillAnalytics.executions(fills).cache()
      val vsVwap = FillAnalytics.summary(FillAnalytics.slippageVsVwap(execs, bars), "takerType", "slippageBp").collect().toSeq
      val vsPrint = FillAnalytics.summary(FillAnalytics.slippageVsPrint(execs, trades), "takerType", "slippageBp").collect().toSeq
      val spreadRows = Seq(5, 60).map { h =>
        val s = FillAnalytics.spreads(fills, prices, h)
        h -> Seq("effectiveBp", "realizedBp", "impactBp")
          .map(c => c -> FillAnalytics.weightedMean(s, "takerType", c, "qtyLots").collect().map(r => r.getString(0) -> (r.getDouble(1), r.getLong(2))).toMap)
          .toMap
      }
      val sizeQ = fills.agg(count(lit(1)), percentile_approx(col("qtyLots").cast("double"), array(lit(0.5), lit(0.9), lit(0.99)), lit(10000)), max("qtyLots")).head()
      val hist = FillAnalytics.sizeHistogram(fills).collect().toSeq
      val secs = (System.nanoTime() - started) / 1e9

      val section = render(day, rates, vsVwap, vsPrint, spreadRows, sizeQ, hist, secs)
      val reportPath = Paths.get(Args.required(o, "report"))
      val existing = if (Files.exists(reportPath)) new String(Files.readAllBytes(reportPath), StandardCharsets.UTF_8) else ""
      val head = existing.indexOf(Marker) match {
        case -1 => existing
        case i  => existing.substring(0, i)
      }
      Files.write(reportPath, (head + section).getBytes(StandardCharsets.UTF_8))
      println(s"updated $reportPath")
      o.get("json").foreach { p =>
        Files.write(Paths.get(p), json(day, rates, vsVwap, vsPrint, spreadRows, hist).getBytes(StandardCharsets.UTF_8))
        println(s"wrote $p")
      }
      println(f"elapsed $secs%.1f s")
    } finally spark.stop()
  }

  private def q(r: Row, i: Int): Seq[Double] = r.getSeq[Double](i)

  private def render(day: String, rates: Seq[Row], vsVwap: Seq[Row], vsPrint: Seq[Row],
                     spreads: Seq[(Int, Map[String, Map[String, (Double, Long)]])], sizeQ: Row, hist: Seq[Row],
                     secs: Double): String = {
    val sb = new StringBuilder
    sb ++= s"$Marker\n\n"
    sb ++= s"Generated by `FillJob` from the C++ engine's replay of $day: real Binance taker flow " +
      "(market and IOC orders) against a seeded **synthetic** resting book. These numbers describe how that " +
      "simulated book absorbs real order flow, not Binance's actual execution quality.\n\n"

    sb ++= "### Fill rate by order type\n\n| Type | Orders | Qty (BTC) | Filled | Fully filled | Not filled at all |\n|---|---|---|---|---|---|\n"
    rates.foreach { r =>
      sb ++= f"| ${r.getString(0)} | ${r.getLong(1)}%,d | ${r.getLong(2) / 1e5}%,.1f | ${100 * r.getDouble(8)}%.2f%% | ${100 * r.getDouble(6)}%.1f%% | ${100 * r.getDouble(7)}%.1f%% |\n"
    }
    sb ++= "\nSynthetic limit orders rest when they do not cross, so their \"fill rate\" is how much maker liquidity was eventually taken before being cancelled.\n\n"

    def slipTable(title: String, rows: Seq[Row], note: String): Unit = {
      sb ++= s"### $title\n\n$note\n\n| Taker type | Executions | Mean (bp) | p10 | p50 | p90 | p99 |\n|---|---|---|---|---|---|---|\n"
      rows.foreach { r =>
        val qs = q(r, 3)
        sb ++= f"| ${r.getString(0)} | ${r.getLong(1)}%,d | ${r.getDouble(2)}%.3f | ${qs(0)}%.3f | ${qs(1)}%.3f | ${qs(2)}%.3f | ${qs(3)}%.3f |\n"
      }
      sb ++= "\n"
    }
    slipTable("Slippage vs 1-minute VWAP", vsVwap,
      "Average execution price of each taker order vs the VWAP of the minute it arrived in (from Phase 2). Positive = the taker paid more (buy) or received less (sell) than VWAP. Quantiles are approximate (relative error 1e-4).")
    slipTable("Slippage vs the real Binance print", vsPrint,
      "Each real order's simulated average price vs the price Binance printed for that same trade. Positive = the simulated book executed worse than the real market did.")

    sb ++= "### Effective spread, realized spread and price impact (quantity-weighted, bp)\n\n"
    sb ++= "Reference price = last-trade price path (no quote data): M0 = previous second, Mh = h seconds later. Effective = 2d(P − M0)/M0, realized = 2d(P − Mh)/M0, impact = effective − realized. The realized spread is what a market maker keeps after the price moves; impact is what it loses to informed flow (adverse selection).\n\n"
    sb ++= "| Horizon | Taker type | Fills | Effective | Realized | Impact |\n|---|---|---|---|---|---|\n"
    spreads.foreach { case (h, m) =>
      m("effectiveBp").keys.toSeq.sorted.foreach { t =>
        val (eff, n) = m("effectiveBp")(t)
        sb ++= f"| ${h}s | $t | $n%,d | $eff%.3f | ${m("realizedBp")(t)._1}%.3f | ${m("impactBp")(t)._1}%.3f |\n"
      }
    }

    // Interpretation, driven by the signs actually observed.
    spreads.find(_._1 == 5).foreach { case (_, m) =>
      val eff = m("effectiveBp").map { case (t, (v, _)) => t -> v }
      val imp = m("impactBp").map { case (t, (v, _)) => t -> v }
      val negative = eff.filter(_._2 < 0).keys.toSeq.sorted
      sb ++= "\n**Reading these numbers.** "
      if (negative.nonEmpty)
        sb ++= s"Negative effective spread for ${negative.mkString(" and ")} means those takers traded at *better* than the pre-trade reference price: " +
          "the synthetic makers quote around the previous second's price, so when the market moves their quotes are stale and incoming flow picks them off. "
      if (imp.values.forall(_ > 0))
        sb ++= "Price impact is positive for every taker type: after a fill, the price keeps moving in the taker's direction, so the makers on the other side lose (adverse selection). " +
          "A real market maker would widen quotes or update them faster than once per second to avoid this.\n"
      else sb ++= "\n"
    }

    val sq = q(sizeQ, 1)
    sb ++= f"\n### Fill-size distribution\n\n${sizeQ.getLong(0)}%,d fills; median ${sq(0)}%.0f lots (${sq(0) / 1e5}%.5f BTC), p90 ${sq(1)}%.0f, p99 ${sq(2)}%.0f, max ${sizeQ.getLong(2)}%,d lots.\n\n"
    sb ++= "| Fill size (lots) | Fills | Share of volume |\n|---|---|---|\n"
    val totalLots = hist.map(_.getLong(2)).sum.toDouble
    hist.foreach { r =>
      val d = r.getInt(0)
      sb ++= f"| ${math.pow(10, d).toLong}%,d – ${math.pow(10, d + 1).toLong - 1}%,d | ${r.getLong(1)}%,d | ${100 * r.getLong(2) / totalLots}%.1f%% |\n"
    }
    sb ++= f"\nComputed in $secs%.1f s (local Spark).\n"
    sb.toString
  }

  private def json(day: String, rates: Seq[Row], vsVwap: Seq[Row], vsPrint: Seq[Row],
                   spreads: Seq[(Int, Map[String, Map[String, (Double, Long)]])], hist: Seq[Row]): String = {
    def slip(rows: Seq[Row]) = rows.map { r =>
      val qs = q(r, 3)
      s""""${r.getString(0)}": {"n": ${r.getLong(1)}, "mean": ${r.getDouble(2)}, "p10": ${qs(0)}, "p50": ${qs(1)}, "p90": ${qs(2)}, "p99": ${qs(3)}}"""
    }.mkString("{", ", ", "}")
    val rateJson = rates.map(r =>
      s""""${r.getString(0)}": {"orders": ${r.getLong(1)}, "qtyLots": ${r.getLong(2)}, "filledLots": ${r.getLong(3)}, "fillRate": ${r.getDouble(8)}, "fullyFilledShare": ${r.getDouble(6)}, "unfilledShare": ${r.getDouble(7)}}"""
    ).mkString("{", ", ", "}")
    val spreadJson = spreads.map { case (h, m) =>
      val byType = m("effectiveBp").keys.toSeq.sorted.map(t =>
        s""""$t": {"fills": ${m("effectiveBp")(t)._2}, "effectiveBp": ${m("effectiveBp")(t)._1}, "realizedBp": ${m("realizedBp")(t)._1}, "impactBp": ${m("impactBp")(t)._1}}"""
      ).mkString("{", ", ", "}")
      s""""${h}s": $byType"""
    }.mkString("{", ", ", "}")
    val histJson = hist.map(r => s"""{"decade": ${r.getInt(0)}, "fills": ${r.getLong(1)}, "lots": ${r.getLong(2)}}""").mkString("[", ", ", "]")
    s"""{
  "day": "$day",
  "fillRates": $rateJson,
  "slippageVsVwapBp": ${slip(vsVwap)},
  "slippageVsPrintBp": ${slip(vsPrint)},
  "spreads": $spreadJson,
  "fillSizeHistogram": $histJson
}
"""
  }
}
